<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;

class RankCheckBatch extends Model
{
    use HasFactory;

    protected $fillable = [
        'batch_id',
        'user_id',
        'client_id',
        'filename',
        'target_domain',
        'target_url',
        'match_type',
        'location',
        'country',
        'language',
        'device',
        'depth',
        'total_keywords',
        'completed_keywords',
        'failed_keywords',
        'top_3_count',
        'top_10_count',
        'page_1_count',
        'unranked_count',
        'status',
        'extracted_keywords',
        'error_message',
        'started_at',
        'completed_at',
    ];

    protected $casts = [
        'extracted_keywords' => 'array',
        'started_at' => 'datetime',
        'completed_at' => 'datetime',
        'total_keywords' => 'integer',
        'completed_keywords' => 'integer',
        'failed_keywords' => 'integer',
        'top_3_count' => 'integer',
        'top_10_count' => 'integer',
        'page_1_count' => 'integer',
        'unranked_count' => 'integer',
        'depth' => 'integer',
    ];

    /**
     * User who dispatched the batch
     */
    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    /**
     * Associated client
     */
    public function client(): BelongsTo
    {
        return $this->belongsTo(Client::class);
    }

    /**
     * All checks generated by this batch
     */
    public function checks(): HasMany
    {
        return $this->hasMany(KeywordRankCheck::class, 'batch_id', 'batch_id');
    }

    /**
     * Calculate progress percentage
     */
    public function getProgressPercentageAttribute(): int
    {
        if ($this->total_keywords <= 0) {
            return ($this->status === 'completed') ? 100 : 0;
        }

        return (int) min(100, round(($this->completed_keywords / $this->total_keywords) * 100));
    }

    /**
     * Scopes
     */
    public function scopePending(Builder $query): Builder
    {
        return $query->where('status', 'pending');
    }

    public function scopeProcessing(Builder $query): Builder
    {
        return $query->where('status', 'processing');
    }

    public function scopeCompleted(Builder $query): Builder
    {
        return $query->where('status', 'completed');
    }
}
